#!/usr/bin/env python3
"""Per-call prices appear only inside the region generated from the szl-gov price catalog.

docs/pricing.md embeds pricing/generated/per-call-table.md from szl-holdings/szl-gov
(rendered from pricing/catalog.yaml, which is checked against the exported Cloudflare
Monetization Gateway rules). These tests keep hand-written per-call prices from
creeping back in beside it.
"""
import re
import unittest
from decimal import Decimal
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = ("<!-- szl:x402-per-call:begin generated by szl-gov tools/pricing_catalog.py "
         "from pricing/catalog.yaml sha256=")
END = "<!-- szl:x402-per-call:end -->"
PER_CALL = re.compile(r"\$0\.\d+")


def read(path):
    return (ROOT / path).read_text(encoding="utf-8")


class TestPricingDoc(unittest.TestCase):
    def region(self):
        doc = read("docs/pricing.md")
        self.assertEqual(doc.count(BEGIN), 1)
        self.assertEqual(doc.count(END), 1)
        return doc, doc[doc.index(BEGIN):doc.index(END) + len(END)]

    def test_generated_region_is_stamped_with_a_catalog_digest(self):
        _, region = self.region()
        self.assertRegex(region[len(BEGIN):len(BEGIN) + 64], r"^[0-9a-f]{64}$")

    def test_each_price_matches_its_atomic_amount(self):
        _, region = self.region()
        rows = re.findall(r"\$(\d+\.\d+) USDC \((\d+) atomic", region)
        self.assertTrue(rows)
        for usd, atomic in rows:
            self.assertEqual(Decimal(usd) * 1_000_000, int(atomic))

    def test_no_per_call_price_outside_the_generated_region(self):
        doc, region = self.region()
        self.assertIsNone(PER_CALL.search(doc.replace(region, "")))
        self.assertIsNone(PER_CALL.search(read("docs/openapi.yaml").replace("$0.02 (20000 atomic USDC", "")))

    def test_no_unverified_payment_is_the_credential_promise(self):
        for path in ("docs/pricing.md", "docs/openapi.yaml"):
            self.assertNotIn("The payment IS the credential", read(path))


if __name__ == "__main__":
    unittest.main()
